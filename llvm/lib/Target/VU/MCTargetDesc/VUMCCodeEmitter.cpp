// Every MCInst emitted for the VU is a BUNDLE holding one upper and one lower
// instruction. It is encoded as a 64-bit little-endian word: the lower
// instruction first, then the upper instruction with the bundle flags.
//
//===----------------------------------------------------------------------===//

#include "MCTargetDesc/VUMCTargetDesc.h"
#include "llvm/MC/MCCodeEmitter.h"
#include "llvm/MC/MCContext.h"
#include "llvm/MC/MCExpr.h"
#include "llvm/MC/MCFixup.h"
#include "llvm/MC/MCInst.h"
#include "llvm/MC/MCInstrInfo.h"
#include "llvm/MC/MCRegisterInfo.h"
#include "llvm/MC/MCSubtargetInfo.h"
#include "llvm/Support/EndianStream.h"

using namespace llvm;

#define DEBUG_TYPE "mccodeemitter"

namespace {
class VUMCCodeEmitter : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  VUMCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
      : MCII(MCII), Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Autogenerated by tblgen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  unsigned getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  unsigned getBranchTargetOpValue(const MCInst &MI, unsigned OpNo,
                                  SmallVectorImpl<MCFixup> &Fixups,
                                  const MCSubtargetInfo &STI) const;
};
} // namespace

MCCodeEmitter *llvm::createVUMCCodeEmitter(const MCInstrInfo &MCII,
                                           MCContext &Ctx) {
  return new VUMCCodeEmitter(MCII, Ctx);
}

void VUMCCodeEmitter::encodeInstruction(const MCInst &MI,
                                        SmallVectorImpl<char> &CB,
                                        SmallVectorImpl<MCFixup> &Fixups,
                                        const MCSubtargetInfo &STI) const {
  assert(MI.getOpcode() == VU::BUNDLE && "VU instructions must be bundled");
  const MCInst &Upper = *MI.getOperand(VU::BundleUpperOp).getInst();
  const MCInst &Lower = *MI.getOperand(VU::BundleLowerOp).getInst();
  unsigned Flags = MI.getOperand(VU::BundleFlagsOp).getImm();

  // The lower word comes first, so its fixups have offset 0. The upper
  // instructions have no fixups.
  uint32_t LowerBits = getBinaryCodeForInstr(Lower, Fixups, STI);
  uint32_t UpperBits = getBinaryCodeForInstr(Upper, Fixups, STI);
  if (Lower.getOpcode() == VU::LOI)
    Flags |= VU::FlagI;
  UpperBits |= Flags << VU::BundleFlagsShift;

  support::endian::write<uint32_t>(CB, LowerBits, endianness::little);
  support::endian::write<uint32_t>(CB, UpperBits, endianness::little);
}

unsigned VUMCCodeEmitter::getMachineOpValue(const MCInst &MI,
                                            const MCOperand &MO,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());

  // The parser only accepts constant expressions for immediates other than
  // branch targets.
  int64_t Value;
  if (MO.isExpr() && MO.getExpr()->evaluateAsAbsolute(Value))
    return static_cast<unsigned>(Value);
  Ctx.reportError(MI.getLoc(), "expected a constant expression");
  return 0;
}

unsigned
VUMCCodeEmitter::getBranchTargetOpValue(const MCInst &MI, unsigned OpNo,
                                        SmallVectorImpl<MCFixup> &Fixups,
                                        const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());

  assert(MO.isExpr() && "Expected an expression for a branch target");
  Fixups.push_back(MCFixup::create(0, MO.getExpr(), VU::fixup_vu_pcrel11,
                                   /*PCRel=*/true));
  return 0;
}

