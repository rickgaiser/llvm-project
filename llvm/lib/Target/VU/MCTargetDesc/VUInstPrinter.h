#ifndef LLVM_LIB_TARGET_VU_MCTARGETDESC_VUINSTPRINTER_H
#define LLVM_LIB_TARGET_VU_MCTARGETDESC_VUINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class VUInstPrinter : public MCInstPrinter {
public:
  VUInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printDest(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printField(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printHex32(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBranchTarget(const MCInst *MI, uint64_t Address, unsigned OpNo,
                         raw_ostream &O);

private:
  /// Print one half of a micro instruction word, without the leading tab.
  /// Flags ("[e]" etc.) are printed right after the mnemonic.
  void printHalf(const MCInst &MI, uint64_t Address, unsigned Flags,
                 raw_ostream &O);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_VU_MCTARGETDESC_VUINSTPRINTER_H
