#ifndef LLVM_LIB_TARGET_DVPVU_MCTARGETDESC_DVPVUINSTPRINTER_H
#define LLVM_LIB_TARGET_DVPVU_MCTARGETDESC_DVPVUINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {
class StringRef;

class DVPVUInstPrinter : public MCInstPrinter {
public:
  DVPVUInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                   const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printDestMask(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBroadcast(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printField(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemVI(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);
  void printRegName(raw_ostream &OS, MCRegister Reg) override;
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_DVPVU_MCTARGETDESC_DVPVUINSTPRINTER_H
